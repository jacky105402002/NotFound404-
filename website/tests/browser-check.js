async page => {
 const assertions=[];const ok=(condition,message)=>{if(!condition)throw new Error(message);assertions.push(message);};
 const errors=[];const badResponses=[];const outbound=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 page.on('response',response=>{if(response.status()>=400)badResponses.push(response.url());});
 page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:4174/'))outbound.push(request.url());});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('http://127.0.0.1:4174/');
 await page.evaluate(()=>document.fonts.ready);
 const widths=[];
 for(const width of [320,390,700,701,768,950,1024,1280,1440,1920]){
   await page.setViewportSize({width,height:900});
   await page.evaluate(()=>window.scrollTo(0,0));
   const geometry=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,heading:document.querySelector('h1').getBoundingClientRect().right,hero:document.querySelector('.hero-copy').getBoundingClientRect().right,form:document.querySelector('#request-form').getBoundingClientRect().right}));
   ok(geometry.scroll<=width,'無水平溢出 '+width);
   ok(geometry.heading<=geometry.hero+1,'主標題留在自身欄位 '+width);
   ok(await page.locator('h1').evaluate(el=>el.scrollWidth<=el.clientWidth+1),'主標文字無裁切 '+width);
   widths.push(geometry);
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'website/qa/desktop.png',fullPage:true});
 await page.locator('.desktop-nav a[href="#services"]').click();
 ok(await page.evaluate(()=>location.hash==='#services'),'桌機服務導覽');
 const previews=page.locator('.case-media button');
 for(let i=0;i<3;i++){
   await previews.nth(i).click();ok(await page.locator('#case-dialog').evaluate(el=>el.open),'案例 '+i+' 開啟');
   await page.locator('#case-dialog-image').evaluate(img=>img.decode());
   ok(await page.locator('#case-dialog-image').evaluate(img=>img.naturalWidth>0),'案例 '+i+' 原始封面載入');
   await page.keyboard.press('Escape');
   ok(await previews.nth(i).evaluate(el=>el===document.activeElement),'案例 '+i+' Escape 返回焦點');
 }
 await page.locator('.desktop-nav a[href="#contact"]').click();
 await page.locator('#preview-submit').click();
 ok(await page.locator('#client-name').evaluate(el=>el===document.activeElement),'空白送出焦點第一錯誤');
 ok((await page.locator('#name-error').textContent()).includes('請填寫'),'稱呼必填錯誤');
 await page.locator('#client-name').fill('測試者');
 await page.locator('#client-email').fill('invalid');
 await page.locator('#preview-submit').click();
 ok(await page.locator('#client-email').getAttribute('aria-invalid')==='true','Email 無效標示');
 await page.locator('#client-email').fill('preview@example.com');
 await page.locator('#project-scope').fill('<img src=x onerror=alert(1)>\n預計十二月上線');
 await page.locator('input[value="SEO 設定"]').check();
 await page.waitForLoadState('networkidle');
 const requests=[];const onRequest=r=>requests.push(r.url());page.on('request',onRequest);
 await page.locator('#preview-submit').click();
 ok(await page.locator('#summary-dialog').evaluate(el=>el.open),'有效資料顯示需求摘要');
 ok((await page.locator('#summary-content').textContent()).includes('SEO 設定'),'摘要反映複選服務');
 ok(await page.locator('#summary-content img').count()===0,'使用者文字不解讀成 HTML');
 ok((await page.locator('#summary-content').textContent()).includes('<img src=x'),'特殊內容以文字呈現');
 for(let i=0;i<5;i++){await page.keyboard.press('Tab');ok(await page.locator('#summary-dialog').evaluate(el=>el.contains(document.activeElement)),'摘要焦點限制於視窗 '+i);}
 await page.screenshot({path:'website/qa/summary.png'});
 await page.getByRole('button',{name:'返回修改'}).click();
 ok(await page.locator('#project-scope').inputValue()==='<img src=x onerror=alert(1)>\n預計十二月上線','返回修改保留草稿');
 ok(requests.length===0,'表單互動沒有網路請求');
 page.off('request',onRequest);
 ok(await page.evaluate(()=>localStorage.length===0&&sessionStorage.length===0&&document.cookie===''),'沒有持久資料或 cookie');
 await page.locator('input[name="services"]').evaluateAll(inputs=>inputs.forEach(input=>{input.checked=false;}));
 await page.locator('#project-scope').fill('');
 await page.locator('#preview-submit').click();
 ok((await page.locator('#summary-content').textContent()).includes('尚未選擇'),'未選服務可正常預覽');
 await page.keyboard.press('Escape');
 await page.reload();await page.evaluate(()=>document.fonts.ready);
 ok(await page.locator('#client-name').inputValue()==='','重新整理清除草稿');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.locator('.mobile-nav a[href="#showcase"]').click();
 ok(await page.evaluate(()=>location.hash==='#showcase'),'手機底部導覽');
 await page.locator('.case-cover').first().scrollIntoViewIfNeeded();
 await page.locator('.case-cover').evaluateAll(images=>Promise.all(images.map(img=>img.decode())));
 const media=await page.locator('.case-cover').evaluateAll(images=>images.map(img=>({src:img.getAttribute('src'),width:img.getBoundingClientRect().width,height:img.getBoundingClientRect().height,naturalWidth:img.naturalWidth,fit:getComputedStyle(img).objectFit})));
 ok(media.every(img=>img.naturalWidth>0&&img.width>0&&img.height>0&&img.fit==='cover'),'手機三張原始封面及填滿 geometry');
 await page.locator('.mobile-nav a[href="#contact"]').click();
 ok(await page.evaluate(()=>location.hash==='#contact'),'手機諮詢導覽');
 await page.screenshot({path:'website/qa/mobile-contact.png'});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'website/qa/mobile.png',fullPage:true});
 ok(await page.locator('.mobile-nav').evaluate(el=>getComputedStyle(el).position==='fixed'),'行動導覽固定且內容留白');
 ok(await page.locator('.cursor').evaluate(el=>getComputedStyle(el).animationName==='none'),'reduced-motion 停用閃爍');
 const fonts=await page.evaluate(()=>['Geist','Noto Sans TC','JetBrains Mono','Material Symbols Sharp'].map(f=>({family:f,loaded:document.fonts.check('14px "'+f+'"')})));
 ok(fonts.every(f=>f.loaded),'四套本機字體可用');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.keyboard.press('Control+Home');
 await page.locator('.skip-link').focus();await page.keyboard.press('Enter');
 ok(await page.evaluate(()=>location.hash==='#main'),'鍵盤 skip link');
 ok(errors.length===0,'無 JavaScript 或 console error: '+errors.join(';'));
 ok(badResponses.length===0,'所有資源 HTTP 成功: '+badResponses.join(';'));
 ok(outbound.length===0,'網站全程無外部請求');
 const noJsContext=await page.context().browser().newContext({javaScriptEnabled:false});
 const noJsPage=await noJsContext.newPage();
 await noJsPage.goto('http://127.0.0.1:4174/');
 ok(await noJsPage.locator('#preview-submit').isDisabled(),'停用 JavaScript 不可送出');
 ok(await noJsPage.locator('noscript').isVisible(),'停用 JavaScript 顯示操作說明');
 await noJsContext.close();
 return {passed:true,assertions,widths,media,fonts,errors,badResponses,outbound};
}
